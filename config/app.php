    'cipher' => 'AES-256-CBC',

    // No .env on the production server (deploys come straight from the
    // `deploy` branch via Hostinger's Git integration, with no SSH and
    // no secrets to paste in by hand). So when APP_KEY isn't set, a
    // random key is generated once on the server and kept in
    // storage/app/private/.app-key, which is never committed to git.
    // Losing it only logs visitors out; this site stores nothing else.
    'key' => env('APP_KEY') ?: (static function (): string {
        $file = storage_path('app/private/.app-key');
        if (is_file($file) && ($stored = trim((string) file_get_contents($file))) !== '') {
            return $stored;
        }
        $key = 'base64:'.base64_encode(random_bytes(32));
        if (! is_dir(dirname($file))) {
            @mkdir(dirname($file), 0750, true);
        }
        // 'x' = create only if missing, so two first requests can't
        // overwrite each other's key.
        if ($handle = @fopen($file, 'x')) {
            fwrite($handle, $key);
            fclose($handle);
            @chmod($file, 0600);

            return $key;
        }

        return is_file($file) ? trim((string) file_get_contents($file)) : $key;
    })(),

    'previous_keys' => [
        ...array_filter(
            explode(',', (string) env('APP_PREVIOUS_KEYS', ''))
        ),
